package ua.kpi.battery_storage

/**
 * Режими відображення застосунку: домашнє завдання та три рівні складності.
 */
enum class DisplayFor(val title: String) {
    /** Домашнє завдання: заряд, потужність, режим роботи та іконка системи. */
    HOME_TASK("Домашнє завдання"),

    /** Базовий рівень: текст, кнопка, колір фону. */
    BASIC_LEVEL("Базовий рівень"),

    /** Середній рівень: змінні дані, випадкові значення, Column і Row. */
    MIDDLE_LEVEL("Середній рівень"),

    /** Просунутий рівень: анімація, State, Material Theme. */
    ADVANCED_LEVEL("Просунутий рівень"),
}
